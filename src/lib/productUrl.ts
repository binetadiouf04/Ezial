import type { Product } from '@/data/products';

// Public product URLs use the product's stable slug (products.slug, generated
// by the database from the name at creation, never changed afterwards):
// /produit/robe-wax-elegante. The id-based form (/produit/<uuid>) stays valid
// everywhere — old links, and any product that has no slug yet.
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isProductUuid(key: string): boolean {
  return UUID_RE.test(key);
}

type ProductUrlFields = Pick<Product, 'id'> & { slug?: string };

// In-app route (no trailing slash, like every other app route).
export function productPath(p: ProductUrlFields): string {
  return `/produit/${p.slug || p.id}`;
}

// Public URL as served and declared canonical (trailing slash, matching the
// static page generated by scripts/prerender-seo.mjs).
export function productPublicPath(p: ProductUrlFields): string {
  return `${productPath(p)}/`;
}

// Resolves the key found in a /produit/<key> URL — a slug or an id.
export function findProductByKey<T extends ProductUrlFields>(products: T[], key: string): T | undefined {
  return products.find((p) => p.id === key || (!!p.slug && p.slug === key));
}
